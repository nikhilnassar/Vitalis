import { Analysis } from './metrics';

const hm = (h: number) => `${Math.floor(h)}h ${Math.round((h % 1) * 60)}m`;
const avg = (a: (number | null | undefined)[]) => {
  const v = a.filter((x): x is number => typeof x === 'number');
  return v.length ? v.reduce((s, x) => s + x, 0) / v.length : undefined;
};
const r1 = (n?: number) => (n === undefined ? '--' : String(Math.round(n * 10) / 10));

/** Plain-text summary of the last 7 days, for sharing or keeping. */
export function buildWeeklyReport(a: Analysis): string {
  const wk = a.days.slice(-7);
  const rec = avg(wk.map((d) => (d.recovery.status === 'ok' ? d.recovery.score : null)));
  const strain = avg(wk.map((d) => (d.strain.hasData ? d.strain.strain : null)));
  const sleepH = avg(wk.map((d) => d.sleep?.hoursAsleep));
  const sleepP = avg(wk.map((d) => d.sleep?.performance));
  const hrv = avg(wk.map((d) => d.recovery.components.hrv?.value));
  const rhr = avg(wk.map((d) => d.recovery.components.rhr?.value));
  const sb = a.sleepBalance;
  const L: string[] = [];
  L.push(`Vitalis weekly report`);
  L.push(`${wk[0]?.date} to ${wk[wk.length - 1]?.date}`);
  L.push('');
  L.push(`Recovery (avg): ${r1(rec)}%`);
  L.push(`Strain (avg): ${r1(strain)} of 21`);
  L.push(`Sleep (avg): ${sleepH === undefined ? '--' : hm(sleepH)}, score ${r1(sleepP)}%`);
  if (sb.nights >= 3) L.push(`Sleep debt: ${sb.debtHours} h${sb.consistency !== undefined ? `, regularity ${sb.consistency}%` : ''}`);
  L.push(`HRV (avg): ${r1(hrv)} ms`);
  L.push(`Resting heart rate (avg): ${r1(rhr)} bpm`);
  if (a.vitals.spo2) L.push(`Overnight SpO2: avg ${a.vitals.spo2.avg}%, lowest ${a.vitals.spo2.min}%`);
  if (a.vitals.temp?.deviation !== undefined) L.push(`Body temperature vs usual: ${a.vitals.temp.deviation > 0 ? '+' : ''}${a.vitals.temp.deviation} °C`);
  for (const t of a.insights.trends.slice(0, 3)) if (t.verdict !== 'unknown' && t.delta != null) L.push(`${t.label}: ${t.verdict} (${t.delta > 0 ? '+' : ''}${t.delta} ${t.unit} vs the prior 30 days)`);
  const done = a.experiments.filter((e) => e.status === 'running' || e.verdict !== 'not-enough-data');
  if (done.length) {
    L.push('');
    for (const e of done.slice(0, 3)) L.push(`Experiment: ${e.exp.mode === 'avoid' ? 'avoid' : 'do'} ${e.exp.habit}, day ${e.dayNumber} of ${e.exp.days}. ${e.summary}`);
  }
  L.push('');
  L.push('Generated by Vitalis from data on this phone. Not a medical device or medical advice.');
  return L.join('\n');
}
